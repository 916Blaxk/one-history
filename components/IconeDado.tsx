export function IconeDado({ estilo }: { estilo: string | null }) {
  /* O id do degradê é por ícone: vários cartões com o mesmo id fariam todos usarem as cores do primeiro. */
  const id = 'g' + useId().replace(/[^a-zA-Z0-9_-]/g, '');
  const forma = estilo ? FORMAS[estilo] : undefined;
  if (!forma) return <IconeD20 />;
  const tinta = `url(#${id})`;
  return (
    <svg viewBox="0 0 24 24" aria-hidden="true" fill="none" stroke={tinta} strokeWidth="1.6" strokeLinecap="round" strokeLinejoin="round">
      <defs>
        <linearGradient id={id} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" style={{ stopColor: 'var(--e-claro)' }} />
          <stop offset=".55" style={{ stopColor: 'var(--e-cor)' }} />
          <stop offset="1" style={{ stopColor: 'var(--e-cor)' }} />
        </linearGradient>
      </defs>
      {forma.p?.map(d => <path key={d} d={d} />)}
      {forma.f?.map(d => <path key={d} d={d} fill={tinta} strokeWidth=".6" />)}
      {forma.c?.map(([x, y, r, cheio]) => <circle key={`${x}-${y}`} cx={x} cy={y} r={r} fill={cheio ? tinta : 'none'} strokeWidth={cheio ? .6 : 1.6} />)}
    </svg>
  );
}

/* As cores do ícone viram variáveis de CSS: o cartão, o brilho e as chamas do crítico leem as mesmas. */
export function coresDoEstilo(id: string | null | undefined): CSSProperties | undefined {
  const e = estiloDado(id);
  return e ? { '--e-cor': e.cor, '--e-claro': e.claro, '--e-escuro': e.escuro } as CSSProperties : undefined;
}
